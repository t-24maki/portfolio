import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { GARDEN_CONFIG } from '../data/miracle-garden.mjs';
import { bestScoreKey } from '../lib/miracle-garden.mjs';

// Bump this when changing the scoring algorithm, not just its parameters.
const protocol = 'garden-spark-1';
const signature = bestScoreKey(GARDEN_CONFIG);
const boardId = `${protocol}-${createHash('sha256').update(signature).digest('hex').slice(0, 24)}`;
const plantCount = Math.min(GARDEN_CONFIG.flowerCount ?? GARDEN_CONFIG.flowers.length, GARDEN_CONFIG.flowers.length) * GARDEN_CONFIG.plantsPerFlowerInFinal;
const schema = { boardId, signature, plantCount, scoreScale: 10 ** GARDEN_CONFIG.scoreDecimals, listLimit: 50 };
const indexes = Array.from({ length: plantCount }, (_, i) => i);
await writeFile(new URL('../data/miracle-garden-ranking-schema.mjs', import.meta.url),
  '// Generated by scripts/prepare-garden-ranking.mjs from the game settings.\nexport const GARDEN_RANKING_SCHEMA = ' + JSON.stringify(schema, null, 2) + ';\n');
await writeFile(new URL('../firestore.rules', import.meta.url), `// Generated by scripts/prepare-garden-ranking.mjs. Deploy after game rule changes.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function currentBoard(boardId) { return boardId == '${boardId}'; }
    function owner(uid) { return request.auth != null && request.auth.uid == uid; }
    function safeUnits(value) { return value is int && value >= 0 && value <= 9007199254740991; }
    function validName(name) {
      return name is string && name == name.trim() && name.matches('[^\\\\p{C}<>]{1,12}');
    }
    function validScore() {
      let d = request.resource.data;
      return d.keys().hasAll(['name', 'scoreUnits', 'lengthUnits', 'achievedAt'])
        && d.keys().hasOnly(['name', 'scoreUnits', 'lengthUnits', 'achievedAt'])
        && validName(d.name)
        && safeUnits(d.scoreUnits)
        && d.lengthUnits is list && d.lengthUnits.size() == ${plantCount}
        && ${indexes.map(i => `safeUnits(d.lengthUnits[${i}])`).join(' && ')}
        && d.scoreUnits == ${indexes.map(i => `d.lengthUnits[${i}]`).join(' + ')}
        && d.achievedAt == request.time;
    }
    match /gardenBoards/{boardId}/scores/{uid} {
      // Counts and document queries share rules. Global counts need no limit.
      // All leaderboard fields are public; the UI still fetches only the top 50.
      allow list: if currentBoard(boardId);
      allow get: if currentBoard(boardId) && owner(uid);
      allow create: if currentBoard(boardId) && owner(uid) && validScore();
      allow update: if currentBoard(boardId) && owner(uid) && (
        (validScore() && request.resource.data.scoreUnits > resource.data.scoreUnits)
        || (validName(request.resource.data.name)
          && request.resource.data.diff(resource.data).affectedKeys().hasOnly(['name']))
      );
      allow delete: if currentBoard(boardId) && owner(uid);
    }
    // Old server-session data and every other path remain inaccessible.
    match /{document=**} { allow read, write: if false; }
  }
}
`);
console.log(`Prepared Spark ranking rules: ${boardId}`);
